CREATE PROC uspAddMedicalRecord
    @AppointmentID INT,
    @VisitDate     DATE,
    @Findings      VARCHAR(MAX),
    @Petweight     DECIMAL(5,2),
    @Remarks       VARCHAR(MAX),
    @DateCreated   DATETIME2(0) = NULL,
    @PetID         INT,
    @StaffID       INT
AS
BEGIN
    SET NOCOUNT ON;

    SET @DateCreated = ISNULL(@DateCreated, GETDATE());

    IF NOT EXISTS (SELECT 1 FROM Pets WHERE pet_id = @PetID)
    BEGIN
        RAISERROR('Pet does not exist.', 16, 1);
        RETURN;
    END

    IF NOT EXISTS (SELECT 1 FROM Staff WHERE staff_id = @StaffID)
    BEGIN
        RAISERROR('Staff does not exist.', 16, 1);
        RETURN;
    END

    IF NOT EXISTS (SELECT 1 FROM Appointments WHERE appointment_id = @AppointmentID)
    BEGIN
        RAISERROR('Appointment does not exist.', 16, 1);
        RETURN;
    END

    IF NOT EXISTS ( SELECT 1 FROM Appointments WHERE appointment_id = @AppointmentID AND pet_id = @PetID )
    BEGIN
        RAISERROR('This pet is not linked to the specified appointment.', 16, 1);
        RETURN;
    END

    BEGIN TRY
        BEGIN TRANSACTION

        INSERT INTO Medical_Records (visit_date, diagnosis, weight_kg, notes, created_at, pet_id, staff_id)
        VALUES (@VisitDate, @Findings, @Petweight, @Remarks, @DateCreated, @PetID, @StaffID);

        DECLARE @RecordID INT = SCOPE_IDENTITY();

        UPDATE Appointments
        SET [status] = 'Completed'
        WHERE appointment_id = @AppointmentID
          AND [status] = 'Scheduled';

        COMMIT TRANSACTION
        PRINT CONCAT('Medical Record #', @RecordID, ' created successfully.');
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;
        PRINT(ERROR_MESSAGE());
    END CATCH
END
