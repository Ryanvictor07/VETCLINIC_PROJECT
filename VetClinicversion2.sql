    @ScheduleID      INT,
    @VaccineName     VARCHAR(50)  = NULL,
    @LastGiven       DATE         = NULL,
    @Interval_Months SMALLINT     = NULL
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS (SELECT 1 FROM Vaccination_Schedule WHERE schedule_id = @ScheduleID)
    BEGIN
        RAISERROR('Vaccination schedule does not exist.', 16, 1);
        RETURN;
    END

    IF @Interval_Months = 0
    BEGIN
        RAISERROR('Interval should be greater than 0', 16, 1);
        RETURN;
    END

    -- Get the CURRENT last_given, in case only the interval is being changed (or vice versa)
    DECLARE @CurrentLastGiven DATE;
    SELECT @CurrentLastGiven = last_given FROM Vaccination_Schedule WHERE schedule_id = @ScheduleID;

    -- Use whichever value was provided, otherwise fall back to the existing one
    DECLARE @EffectiveLastGiven DATE = ISNULL(@LastGiven, @CurrentLastGiven);

    -- Only recalculate next_due if last_given OR interval actually changed
    DECLARE @NextDue DATE;
    IF @LastGiven IS NOT NULL OR @Interval_Months IS NOT NULL
    BEGIN
        -- Need an interval to recalculate; if none was passed this time, we can't safely recompute
        IF @Interval_Months IS NULL
        BEGIN
            RAISERROR('Interval_Months is required when updating LastGiven, to recalculate NextDue.', 16, 1);
            RETURN;
        END

        SET @NextDue = dbo.CalculateNextVaccineDueDate(@EffectiveLastGiven, @Interval_Months);
    END

    BEGIN TRY
        BEGIN TRANSACTION

        UPDATE Vaccination_Schedule
        SET vaccine_name = ISNULL(@VaccineName, vaccine_name),
            last_given    = ISNULL(@LastGiven, last_given),
            next_due      = ISNULL(@NextDue, next_due)
        WHERE schedule_id = @ScheduleID;

        COMMIT TRANSACTION
        PRINT 'Vaccination schedule updated successfully.';
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;
        PRINT(ERROR_MESSAGE());
    END CATCH
