CREATE PROC uspUpdateAppointment
    @AppointmentID INT,
    @Date          DATE         = NULL,
    @Time          TIME         = NULL,
    @Reason        VARCHAR(MAX) = NULL,
    @Status        VARCHAR(50)  = NULL,
    @StaffID       INT          = NULL
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS (SELECT 1 FROM Appointments WHERE appointment_id = @AppointmentID)
    BEGIN
        RAISERROR('Appointment does not exist.', 16, 1);
        RETURN;
    END

    -- Get the current values, so we know what's ACTUALLY changing
    DECLARE @CurrentDate    DATE;
    DECLARE @CurrentTime    TIME;
    DECLARE @CurrentStaffID INT;

    SELECT
        @CurrentDate    = appointment_date,
        @CurrentTime    = appointment_time,
        @CurrentStaffID = staff_id
    FROM Appointments
    WHERE appointment_id = @AppointmentID;

    DECLARE @EffectiveDate    DATE = ISNULL(@Date, @CurrentDate);
    DECLARE @EffectiveTime    TIME = ISNULL(@Time, @CurrentTime);
    DECLARE @EffectiveStaffID INT  = ISNULL(@StaffID, @CurrentStaffID);

    -- Only re-check slot availability if date, time, or staff actually changed
    IF (@Date IS NOT NULL OR @Time IS NOT NULL OR @StaffID IS NOT NULL)
    BEGIN
        IF EXISTS (
            SELECT 1 FROM Appointments
            WHERE staff_id = @EffectiveStaffID
              AND appointment_date = @EffectiveDate
              AND appointment_time = @EffectiveTime
              AND status <> 'Cancelled'
              AND appointment_id <> @AppointmentID   -- exclude the appointment being updated itself
        )
        BEGIN
            RAISERROR('This staff member already has an appointment at this date and time.', 16, 1);
            RETURN;
        END
    END

    BEGIN TRY
        BEGIN TRANSACTION

        UPDATE Appointments
        SET appointment_date = @EffectiveDate,
            appointment_time = @EffectiveTime,
            reason           = ISNULL(@Reason, reason),
            status           = ISNULL(@Status, status),
            staff_id         = @EffectiveStaffID
        WHERE appointment_id = @AppointmentID;

        COMMIT TRANSACTION
        PRINT 'Appointment updated successfully.';
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;
        PRINT(ERROR_MESSAGE());
    END CATCH
END
