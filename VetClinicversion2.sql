CREATE FUNCTION IsSlotAvailable
(
@staff_id int,
@date date,
@time time(0)
)
RETURNS varchar(50)
AS
BEGIN
	DECLARE @slot varchar(50) = 'Available'

    IF EXISTS (
        SELECT 1 FROM Appointments
        WHERE staff_id = @staff_id
            AND appointment_date = @date
            AND appointment_time = @time
            AND status <> 'Cancelled'
    )
    BEGIN   
        SET @slot = 'Booked'
    END 

    RETURN @slot
END
